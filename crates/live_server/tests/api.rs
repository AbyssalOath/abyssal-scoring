//! End-to-end coverage of the live-scoring HTTP + WS API against a
//! real (in-memory) `AppService` -- no Tauri, no Swift, just this
//! crate's own router. This is what "curl/websocat-testable" means in
//! practice: everything here could equally be driven by hand with
//! curl against a real running process.

use std::sync::Arc;
use std::time::Duration;

use axum::body::Body;
use axum::http::{Request, StatusCode};
use chrono::NaiveDate;
use futures_util::StreamExt;
use http_body_util::BodyExt;
use models::{Competition, Event, Judge, JudgeRole, Participant, Sport};
use serde_json::{json, Value};
use server::AppService;
use tower::ServiceExt;

async fn seed() -> (Arc<AppService>, Competition, Judge, Event, Participant) {
    let service = Arc::new(AppService::open_in_memory().await.unwrap());
    let competition = service
        .create_competition(
            "Test Meet",
            Sport::Gymnastics,
            NaiveDate::from_ymd_opt(2026, 1, 1).unwrap(),
        )
        .await
        .unwrap();
    let judge = service
        .add_judge(competition.id, "Pat Judge", JudgeRole::Execution)
        .await
        .unwrap();
    let event = service.add_event(competition.id, "Beam", 1).await.unwrap();
    let participant = service
        .add_participant(competition.id, "Jane", "Doe")
        .await
        .unwrap();
    (service, competition, judge, event, participant)
}

async fn body_json(response: axum::response::Response) -> Value {
    let bytes = response.into_body().collect().await.unwrap().to_bytes();
    serde_json::from_slice(&bytes).unwrap()
}

#[tokio::test]
async fn pairing_auth_and_score_submission_round_trip() {
    let (service, competition, judge, event, participant) = seed().await;
    let app = live_server::router(service.clone());

    // A pairing code is generated by the desktop (here, directly
    // through `AppService`, exactly as the "Pair iPad" control-panel
    // button will) and redeemed over HTTP by the device.
    let pairing = service.create_pairing_code(judge.id).await.unwrap();

    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/v1/pair")
                .header("content-type", "application/json")
                .body(Body::from(
                    json!({ "code": pairing.code, "deviceName": "Test iPad" }).to_string(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let pair_body = body_json(response).await;
    let token = pair_body["token"].as_str().unwrap().to_string();
    assert_eq!(pair_body["judge"]["id"], json!(judge.id));

    // The same code can't be redeemed a second time.
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/v1/pair")
                .header("content-type", "application/json")
                .body(Body::from(
                    json!({ "code": pairing.code, "deviceName": "Second iPad" }).to_string(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::BAD_REQUEST);

    // Score submission is auth-protected: rejects no token and a bad
    // token (the auth extractor runs before the JSON body is parsed,
    // so an empty/invalid body doesn't interfere with this check).
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/v1/scores/gymnastics-panel")
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::UNAUTHORIZED);

    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/v1/scores/gymnastics-panel")
                .header("authorization", "Bearer not-a-real-token")
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::UNAUTHORIZED);

    // Events/participants are public (a spectator app needs names to
    // label the scoreboard, and this is the same info already shown
    // on the TV/rotation sheet) - no token required.
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .uri(format!("/api/v1/competitions/{}/events", competition.id.0))
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let events = body_json(response).await;
    assert_eq!(events[0]["id"], json!(event.id));

    // Submitting a score computes the result AND puts it up on the
    // live scoreboard, same as the desktop's "Submit score" button.
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/v1/scores/gymnastics-panel")
                .header("content-type", "application/json")
                .header("authorization", format!("Bearer {token}"))
                .body(Body::from(
                    json!({
                        "eventId": event.id,
                        "participantId": participant.id,
                        "apparatus": "balance_beam",
                        "difficultyScore": 5.0,
                        "judgeScores": [{ "judgeId": null, "deductions": [] }],
                        "neutralDeductions": 0.0,
                    })
                    .to_string(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let result = body_json(response).await;
    // D 5.0 + E 10.0 (no deductions) - ND 0.0.
    assert_eq!(result["final_value"], json!(15.0));
    // No `judgeId` was given for the single judge score -- it should
    // have been filled in from the authenticated device.
    assert_eq!(result["detail"]["judge_execution_scores"], json!([10.0]));

    let scoreboard = service.get_scoreboard_state(competition.id).await.unwrap();
    assert_eq!(scoreboard.current_participant_id, Some(participant.id));
    assert_eq!(scoreboard.display_mode, models::DisplayMode::ShowingResult);

    // Public scoreboard endpoint needs no auth.
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .uri(format!("/api/v1/scoreboard/{}", competition.id.0))
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);

    // Public competition list -- what a spectator app's picker uses.
    let response = app
        .oneshot(
            Request::builder()
                .uri("/api/v1/competitions")
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(response.status(), StatusCode::OK);
    let competitions = body_json(response).await;
    assert_eq!(competitions[0]["id"], json!(competition.id));
}

#[tokio::test]
async fn websocket_pushes_scoreboard_state_when_it_changes() {
    let (service, competition, _judge, event, participant) = seed().await;
    let app = live_server::router(service.clone());

    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    tokio::spawn(async move {
        axum::serve(listener, app).await.unwrap();
    });

    let ws_url = format!("ws://{addr}/api/v1/ws/scoreboard/{}", competition.id.0);
    let (mut ws_stream, _) = tokio_tungstenite::connect_async(ws_url).await.unwrap();

    let first = tokio::time::timeout(Duration::from_secs(2), ws_stream.next())
        .await
        .expect("timed out waiting for initial scoreboard push")
        .expect("stream ended")
        .expect("websocket error");
    let first_json: Value = serde_json::from_str(&first.into_text().unwrap()).unwrap();
    assert_eq!(first_json["type"], "scoreboard_state");
    assert_eq!(first_json["payload"]["display_mode"], "idle");

    // A change made directly through `AppService` -- exactly what
    // happens when either the desktop control panel or a judge's
    // REST submission mutates scoreboard state -- shows up over the
    // socket without the client needing to reconnect or re-poll.
    service
        .set_current_participant(competition.id, event.id, participant.id)
        .await
        .unwrap();

    let second = tokio::time::timeout(Duration::from_secs(2), ws_stream.next())
        .await
        .expect("timed out waiting for updated scoreboard push")
        .expect("stream ended")
        .expect("websocket error");
    let second_json: Value = serde_json::from_str(&second.into_text().unwrap()).unwrap();
    assert_eq!(second_json["payload"]["display_mode"], "in_progress");
    assert_eq!(
        second_json["payload"]["current_participant_id"],
        json!(participant.id)
    );
}
